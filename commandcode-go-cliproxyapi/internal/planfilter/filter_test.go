// TestFilterMatchesReferenceForEveryPlan asserts, for each plan, that our
// filter keeps exactly the models the reference keeps - no more, no less.
func TestFilterMatchesReferenceForEveryPlan(t *testing.T) {
	for planID, tier := range planTierByName {
		want, ok := wantVisibleByPlan[planID]
		if !ok {
			t.Fatalf("no reference expectation for %s", planID)
		}
		got := FilterModels(liveCatalog87, []*BillingAccess{{TierWeight: tier}})
		gotSet, wantSet := setOf(got), setOf(want)

		for _, id := range got {
			if _, ok := wantSet[id]; !ok {
				t.Errorf("%s: kept a model the reference hides: %s", planID, id)
			}
		}
		for _, id := range want {
			if _, ok := gotSet[id]; !ok {
				t.Errorf("%s: hid a model the reference keeps: %s", planID, id)
			}
		}
		if len(got) != len(want) {
			t.Errorf("%s: count %d, reference %d", planID, len(got), len(want))
		}
	}
}

