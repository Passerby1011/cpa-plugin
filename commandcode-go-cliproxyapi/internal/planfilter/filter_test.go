// mechanical failure modes: a truncated table, or a tier name that is not on
// the scale.
func TestTableSnapshotIntegrity(t *testing.T) {
	const wantEntries = 85
	if len(knownPlans) != wantEntries {
		t.Fatalf("knownPlans has %d entries, want %d (table truncated during a port?)", len(knownPlans), wantEntries)
	}
	for id, tier := range knownPlans {
		if _, ok := planOrder[tier]; !ok {
			t.Errorf("model %q has tier %q which is not on the plan scale", id, tier)
		}
	}
	for _, tier := range planTierOrder {
		if _, ok := planOrder[tier]; !ok {
			t.Errorf("plan scale lists %q but planOrder has no rank for it", tier)
		}
	}
	if len(planOrder) != len(planTierOrder) {
		t.Errorf("planOrder has %d ranks for %d tiers", len(planOrder), len(planTierOrder))
	}
}
