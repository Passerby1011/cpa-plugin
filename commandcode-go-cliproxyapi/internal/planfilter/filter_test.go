// TestFilterFailsOpen covers every "uncertainty keeps the model" rule. Each of
// these hiding a model would be a silent, hard-to-notice loss.
func TestFilterFailsOpen(t *testing.T) {
	all := len(liveCatalog87)

	if n := len(FilterModels(liveCatalog87, nil)); n != all {
		t.Errorf("no accounts: kept %d, want all %d (empty pool shows everything)", n, all)
	}
	if n := len(FilterModels(liveCatalog87, []*BillingAccess{})); n != all {
		t.Errorf("empty pool: kept %d, want all %d", n, all)
	}
	if n := len(FilterModels(liveCatalog87, []*BillingAccess{{}})); n != all {
		t.Errorf("unknown tier: kept %d, want all %d", n, all)
	}
	if n := len(FilterModels(liveCatalog87, []*BillingAccess{{TierWeight: intp(0), OnDemandCredits: 5}})); n != all {
		t.Errorf("on-demand credits: kept %d, want all %d", n, all)
	}
	// A model absent from the table must stay visible: the table can lag
	// upstream, and hiding a brand-new model would be the worst case.
	if !ModelVisibleInPlan("brand-new-model-not-in-table", &BillingAccess{TierWeight: intp(0)}) {
		t.Error("a model missing from the table was hidden; unknown models must fail open")
	}
	// An unrecognised planId must not be treated as the lowest tier.
	if !ModelVisibleInPlan("claude-opus-5-5", AccessFor(SubscriptionPlanFor("some-future-plan"), 0)) {
		t.Error("unknown planId hid a model; unknown plans must fail open")
	}
}

// TestFilterUsesUnionAcrossAccounts pins the pool rule the operator asked for:
// with several plans, a model shows if ANY of them includes it.
func TestFilterUsesUnionAcrossAccounts(t *testing.T) {
	pool := []*BillingAccess{{TierWeight: intp(0)}, {TierWeight: intp(2)}} // Go + Pro
	got := FilterModels(liveCatalog87, pool)
	proOnly := FilterModels(liveCatalog87, []*BillingAccess{{TierWeight: intp(2)}})
	if len(got) != len(proOnly) {
		t.Fatalf("Go+Pro union kept %d, Pro alone %d (Pro superset of Go, so they must match)", len(got), len(proOnly))
	}
	// The union must be strictly larger than Go alone, or the rule is not
	// actually unioning.
	goOnly := FilterModels(liveCatalog87, []*BillingAccess{{TierWeight: intp(0)}})
	if len(got) <= len(goOnly) {
		t.Errorf("union (%d) is not larger than Go alone (%d)", len(got), len(goOnly))
	}
}

// TestSubscriptionPlanResolution pins longest-prefix matching: "individual-goat"
// must not resolve as "individual-go".
func TestSubscriptionPlanResolution(t *testing.T) {
	cases := map[string]struct {
		name string
		tier int
	}{
		"individual-go":       {"Go", 0},
		"individual-go-v1":    {"Go", 0},
		"individual-goat":     {"GOAT", 1},
		"individual-pro":      {"Pro", 2},
		"individual-pro-v1":   {"Pro", 2},
		"individual-provider": {"Provider", 3},
		"individual-max":      {"Max", 4},
		"individual-ultra":    {"Ultra", 4},
		"teams-pro":           {"Teams Pro", 2},
		"individual_goat":     {"GOAT", 1}, // underscore normalisation
	}
	for id, want := range cases {
		p := SubscriptionPlanFor(id)
		if p == nil {
			t.Errorf("%s: no plan resolved", id)
			continue
		}
		if p.Name != want.name || p.TierWeight != want.tier {
			t.Errorf("%s: got %s/%d, want %s/%d", id, p.Name, p.TierWeight, want.name, want.tier)
		}
	}
	if SubscriptionPlanFor("nonsense") != nil {
		t.Error("an unrecognised planId resolved to a plan; it must return nil so callers fail open")
	}
}

